import { notFound } from "next/navigation";
import { prisma } from "@/lib/db/prisma";
import { auth } from "@/lib/auth/config";
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Map, Calendar, Target } from "lucide-react";

export default async function RoadmapPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const session = await auth();
  const project = await prisma.project.findFirst({ where: { id, ownerId: session!.user.id } });
  if (!project) notFound();

  const pmRun = await prisma.agentRun.findFirst({
    where: { projectId: id, agentType: "PRODUCT_MANAGER", status: "COMPLETED" },
    orderBy: { createdAt: "desc" },
  });
  const roadmap = (pmRun?.output as any)?.productRoadmap || [];

  return (
    <div className="space-y-6">
      <div>
        <h1 className="font-display text-3xl font-bold tracking-tight">Roadmap</h1>
        <p className="mt-1 text-sm text-muted-foreground">Quarterly themes generated by your Product Manager agent.</p>
      </div>

      {roadmap.length === 0 ? (
        <Card>
          <CardContent className="flex flex-col items-center justify-center p-16 text-center">
            <Map className="h-10 w-10 text-muted-foreground/50" />
            <h2 className="mt-4 font-display text-xl font-bold">No roadmap yet</h2>
            <p className="mt-1 max-w-md text-sm text-muted-foreground">Run the Product Manager agent to generate a quarterly roadmap.</p>
          </CardContent>
        </Card>
      ) : (
        <div className="grid gap-4 md:grid-cols-2 lg:grid-cols-4">
          {roadmap.map((q: any) => (
            <Card key={q.quarter} className="border-border/60">
              <CardHeader>
                <div className="flex items-center justify-between">
                  <Badge variant="gradient">{q.quarter}</Badge>
                  <Target className="h-4 w-4 text-muted-foreground" />
                </div>
                <CardTitle className="mt-2">{q.theme}</CardTitle>
              </CardHeader>
              <CardContent>
                <ul className="space-y-2 text-sm">
                  {q.items.map((item: string) => (
                    <li key={item} className="flex items-center gap-2">
                      <div className="h-1.5 w-1.5 rounded-full bg-fuchsia-500" />
                      {item}
                    </li>
                  ))}
                </ul>
              </CardContent>
            </Card>
          ))}
        </div>
      )}
    </div>
  );
}
